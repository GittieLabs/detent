//! Generates `firmware/include/detent_protocol.h` from this crate's constants.
//! Run `scripts/gen-header.sh`; a test fails if the committed header drifts.

use crate::codec::{
    ButtonAction, ControlKind, EncoderMode, KIND_ENCODER_WITH_PUSH, MAX_CONTROLS,
    MAX_INJECT_EVENTS, MAX_LABEL_LEN, MAX_STATUS_LEN,
};
use crate::{ids, msg, HEADER_LEN, MAX_PAYLOAD_LEN, PROTOCOL_VERSION, REPORT_LEN};
use crate::{CONSUMER_REPORT_ID, USAGE, USAGE_PAGE, VENDOR_REPORT_ID};

/// The full text of `detent_protocol.h`.
pub fn c_header() -> String {
    let types: String = msg::ALL
        .iter()
        .map(|(id, name)| format!("#define DETENT_MSG_{name} 0x{id:02X}\n"))
        .collect();
    let identity: String = ids::MODELS
        .iter()
        .enumerate()
        .map(|(i, m)| {
            let branch = if i == 0 { "#if" } else { "#elif" };
            format!(
                "{branch} defined(DETENT_BOARD_{board})\n\
                 #define DETENT_USB_VID 0x{vid:04X}\n\
                 #define DETENT_USB_PID 0x{pid:04X}\n\
                 #define DETENT_MODEL_NAME \"{name}\"\n",
                board = m.board,
                vid = m.vid,
                pid = m.pid,
                name = m.name,
            )
        })
        .collect();
    let (mode_volume, mode_menu, mode_mapped) = (
        EncoderMode::Volume as u8,
        EncoderMode::Menu as u8,
        EncoderMode::Mapped as u8,
    );
    let (kind_button, kind_encoder) = (ControlKind::Button as u8, ControlKind::Encoder as u8);
    let (action_down, action_up, action_long) = (
        ButtonAction::Down as u8,
        ButtonAction::Up as u8,
        ButtonAction::LongPress as u8,
    );

    format!(
        "\
// GENERATED by scripts/gen-header.sh from the protocol crate. Do not edit.
// Source of truth: protocol/src/. Wire format: docs/protocol.md.

#ifndef DETENT_PROTOCOL_H
#define DETENT_PROTOCOL_H

#define DETENT_PROTOCOL_VERSION {PROTOCOL_VERSION}

// Report layout
#define DETENT_REPORT_LEN {REPORT_LEN}
#define DETENT_HEADER_LEN {HEADER_LEN}
#define DETENT_MAX_PAYLOAD_LEN {MAX_PAYLOAD_LEN}
#define DETENT_USAGE_PAGE 0x{USAGE_PAGE:04X}
#define DETENT_USAGE 0x{USAGE:02X}
#define DETENT_VENDOR_REPORT_ID {VENDOR_REPORT_ID}
#define DETENT_CONSUMER_REPORT_ID {CONSUMER_REPORT_ID}

// USB identity (D-112, D-113): each board's local IDs and model name, chosen
// by its -DDETENT_BOARD_* flag. Hosts recognize a unit by its product string
// `Detent <model name>` and HELLO, not by these IDs.
{identity}#endif

// Message types: device to app 0x01..0x7F, app to device 0x80..0xFF
{types}
// Codec limits
#define DETENT_MAX_CONTROLS {MAX_CONTROLS}
#define DETENT_MAX_LABEL_LEN {MAX_LABEL_LEN}
#define DETENT_MAX_STATUS_LEN {MAX_STATUS_LEN}
#define DETENT_MAX_INJECT_EVENTS {MAX_INJECT_EVENTS}

// Field values
#define DETENT_ENCODER_MODE_VOLUME {mode_volume}
#define DETENT_ENCODER_MODE_MENU {mode_menu}
#define DETENT_ENCODER_MODE_MAPPED {mode_mapped}
#define DETENT_KIND_BUTTON {kind_button}
#define DETENT_KIND_ENCODER {kind_encoder}
// v2: an encoder entry whose third byte is its push switch's control ID
#define DETENT_KIND_ENCODER_WITH_PUSH {KIND_ENCODER_WITH_PUSH}
#define DETENT_ACTION_DOWN {action_down}
#define DETENT_ACTION_UP {action_up}
#define DETENT_ACTION_LONG_PRESS {action_long}
#endif  // DETENT_PROTOCOL_H
"
    )
}
