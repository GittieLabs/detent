//! Generates `firmware/include/detent_protocol.h` from this crate's constants.
//! Run `scripts/gen-header.sh`; a test fails if the committed header drifts.

use crate::{ids, msg, HEADER_LEN, MAX_PAYLOAD_LEN, PROTOCOL_VERSION, REPORT_LEN};
use crate::{CONSUMER_REPORT_ID, USAGE, USAGE_PAGE, VENDOR_REPORT_ID};

/// The full text of `detent_protocol.h`.
pub fn c_header() -> String {
    let types: String = msg::ALL
        .iter()
        .map(|(id, name)| format!("#define DETENT_MSG_{name} 0x{id:02X}\n"))
        .collect();
    let vid = ids::VID;
    let pid = ids::PID;

    format!(
        "\
// GENERATED by scripts/gen-header.sh from the protocol crate. Do not edit.
// Source of truth: protocol/src/. Wire format: docs/protocol.md.

#ifndef DETENT_PROTOCOL_H
#define DETENT_PROTOCOL_H

#define DETENT_PROTOCOL_VERSION {PROTOCOL_VERSION}

// Report layout
#define DETENT_REPORT_LEN {REPORT_LEN}
#define DETENT_HEADER_LEN {HEADER_LEN}
#define DETENT_MAX_PAYLOAD_LEN {MAX_PAYLOAD_LEN}
#define DETENT_USAGE_PAGE 0x{USAGE_PAGE:04X}
#define DETENT_USAGE 0x{USAGE:02X}
#define DETENT_VENDOR_REPORT_ID {VENDOR_REPORT_ID}
#define DETENT_CONSUMER_REPORT_ID {CONSUMER_REPORT_ID}

// USB identity
#define DETENT_USB_VID 0x{vid:04X}
#define DETENT_USB_PID 0x{pid:04X}  // PLACEHOLDER until the Espressif usb-pids allocation

// Message types: device to app 0x01..0x7F, app to device 0x80..0xFF
{types}
#endif  // DETENT_PROTOCOL_H
"
    )
}
